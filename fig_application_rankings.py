# FIGURE 3 — Product radar charts
# ════════════════════════════════════════════════════════════
def fig_radar(scores_df: pd.DataFrame):
    products   = sorted(scores_df["product"].unique())
    apps       = APPS_ORDERED
    n_apps     = len(apps)
    angles     = np.linspace(0, 2 * np.pi, n_apps, endpoint=False).tolist()
    angles    += angles[:1]
    app_labels = [APP_SHORT.get(a, a).replace("\n", " ") for a in apps]

    score_floor = max(0.0, scores_df["score"].min() - 0.06)
    score_ceil  = min(1.0, scores_df["score"].max() + 0.02)

    fig, axs = plt.subplots(
        2, 3, figsize=(16, 10.5),
        subplot_kw=dict(polar=True)
    )
    fig.patch.set_facecolor("white")

    for pi, (prod, ax) in enumerate(zip(products, axs.flat)):
        ax.set_facecolor("none")
        ax.set_theta_offset(np.pi / 2)
        ax.set_theta_direction(-1)
        ax.set_ylim(score_floor, score_ceil)

        rticks = np.linspace(score_floor, score_ceil, 4)
        ax.set_yticks(rticks)
        ax.set_yticklabels([f"{v:.2f}" for v in rticks],
                           fontsize=6.2, color="#9CA3AF")
        ax.set_xticks(angles[:-1])
        ax.set_xticklabels(app_labels, fontsize=7.8, color="#374151")
        ax.tick_params(axis="x", pad=9)
        ax.grid(color="#E5E7EB", linewidth=0.8)
        ax.spines["polar"].set_color("#D1D5DB")

        for zone in ZONES:
            sub = scores_df[
                (scores_df["product"] == prod) &
                (scores_df["zone"]    == zone)
            ]
            vals = []
            for app in apps:
                row = sub[sub["app"] == app]
                vals.append(row["score"].values[0]
                            if not row.empty else score_floor)
            vals += vals[:1]

            zcolor = ZONE_COLORS.get(zone, "#888")
            ax.plot(angles, vals, color=zcolor,
                    linewidth=1.8, alpha=0.92, zorder=3)

        ax.set_title(PROD_LABELS.get(prod, prod),
                     fontsize=11.5, fontweight="bold",
                     color=PROD_COLORS.get(prod, "#1C2D40"), pad=15)

    zone_handles = [
        mpatches.Patch(facecolor=ZONE_COLORS[z], alpha=0.87,
                       label=z, linewidth=0)
        for z in ZONES
    ]
    fig.legend(handles=zone_handles, title="Ecological zone",
               title_fontsize=9, loc="lower center",
               bbox_to_anchor=(0.5, -0.02), ncol=5, fontsize=9,
               frameon=True, framealpha=0.96, edgecolor="#D0D7E0")

    fig.suptitle(
        "Application-weighted composite score profiles by product and ecological zone\n"
        f"Each axis = one management application  |  "
        f"Radial scale: {score_floor:.2f}–{score_ceil:.2f}  |  "
        "τ = 1.0 mm/day  |  West Africa 2001–2020",
        fontsize=11.5, fontweight="bold", color="#1C2D40", y=1.01
    )

    plt.tight_layout(rect=[0, 0.07, 1, 1])
    out = FIGS_DIR / "fig_app03_product_radar.png"
    fig.savefig(out, dpi=300, bbox_inches="tight",
                facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


