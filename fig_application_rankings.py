# FIGURE 2 — Zone bar panels (y-axis zoomed to actual range)
# ════════════════════════════════════════════════════════════
def fig_zone_bars(scores_df: pd.DataFrame):
    apps     = APPS_ORDERED
    zones    = ZONES
    products = sorted(scores_df["product"].unique())

    score_min = scores_df["score"].min()
    score_max = scores_df["score"].max()
    y_lo = max(0.0, score_min - 0.04)
    y_hi = min(1.02, score_max + 0.03)

    fig = plt.figure(figsize=(18, 14))
    fig.patch.set_facecolor("white")

    gs = GridSpec(3, 3, figure=fig,
                  hspace=0.55, wspace=0.30,
                  left=0.06, right=0.97,
                  top=0.92, bottom=0.10)

    panel_positions = [
        gs[0,0], gs[0,1], gs[0,2],
        gs[1,0], gs[1,1], gs[1,2],
        gs[2,0],
    ]

    bar_w  = 0.13
    x_base = np.arange(len(zones))

    for pi, (app, pos) in enumerate(zip(apps, panel_positions)):
        ax = fig.add_subplot(pos)
        ax.set_facecolor("none")
        for spine in ax.spines.values():
            spine.set_edgecolor("#D0D7E0")
            spine.set_linewidth(0.8)

        for pi2, prod in enumerate(products):
            offsets = x_base + (pi2 - len(products) / 2 + 0.5) * bar_w
            vals = []
            for zone in zones:
                sub = scores_df[
                    (scores_df["app"]     == app)  &
                    (scores_df["zone"]    == zone) &
                    (scores_df["product"] == prod)
                ]
                vals.append(sub["score"].values[0]
                            if not sub.empty else np.nan)

            ax.bar(offsets, vals,
                   width=bar_w * 0.88,
                   color=PROD_COLORS.get(prod, "#888"),
                   alpha=0.86, zorder=3, linewidth=0)

        ax.set_ylim(y_lo, y_hi)
        ax.yaxis.grid(True, color="#E5E7EB", linewidth=0.6, zorder=0)
        ax.set_axisbelow(True)
        ax.set_xticks(x_base)
        ax.set_xticklabels(
            [z.replace("Guineo-Congolean", "G-Congolean") for z in zones],
            fontsize=8, rotation=20, ha="right", color="#1C2D40"
        )
        tick_vals = np.linspace(y_lo, y_hi, 5)
        ax.set_yticks(tick_vals)
        ax.set_yticklabels([f"{v:.2f}" for v in tick_vals],
                           fontsize=7.5, color="#6B7280")
        ax.set_title(app, fontsize=10, fontweight="bold",
                     color="#1C2D40", pad=6)
        if pi % 3 == 0:
            ax.set_ylabel("Composite score", fontsize=8, color="#6B7280")

    # Legend
    legend_ax = fig.add_subplot(gs[2, 1:])
    legend_ax.set_visible(False)
    handles = [
        mpatches.Patch(facecolor=PROD_COLORS[p], alpha=0.86,
                       label=PROD_LABELS.get(p, p), linewidth=0)
        for p in products
    ]
    fig.legend(handles=handles, title="Precipitation product",
               title_fontsize=9.5, loc="lower right",
               bbox_to_anchor=(0.97, 0.04), ncol=3, fontsize=9,
               frameon=True, framealpha=0.96, edgecolor="#D0D7E0",
               handlelength=1.4, handleheight=1.0)

    for zi, zone in enumerate(zones):
        zx = 0.06 + zi * (0.60 / len(zones))
        fig.text(zx, 0.026, "●", fontsize=12,
                 color=ZONE_COLORS.get(zone, "#888"),
                 ha="center", transform=fig.transFigure)
        fig.text(zx, 0.008,
                 zone.replace("Guineo-Congolean", "G-Congolean"),
                 fontsize=7.5, ha="center",
                 color="#1C2D40", transform=fig.transFigure)

    fig.suptitle(
        "Application-weighted composite scores by product, ecological zone, and management application\n"
        f"Y-axis: {y_lo:.2f}–{y_hi:.2f} (zoomed to actual range)  |  "
        "τ = 1.0 mm/day  |  West Africa 2001–2020",
        fontsize=11.5, fontweight="bold", color="#1C2D40", y=0.97
    )

    out = FIGS_DIR / "fig_app02_zone_bar_panels.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


