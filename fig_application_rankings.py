# FIGURE 1 — Recommendation heatmap
# ════════════════════════════════════════════════════════════
def fig_heatmap(scores_df: pd.DataFrame):
    zones   = ZONES
    apps    = APPS_ORDERED
    n_zones = len(zones)
    n_apps  = len(apps)
    cell_w  = 1.0
    cell_h  = 0.82

    fig, ax = plt.subplots(figsize=(14, 8))
    fig.patch.set_facecolor("white")
    ax.set_facecolor("none")

    for ai, app in enumerate(apps):
        for zi, zone in enumerate(zones):
            sub = scores_df[
                (scores_df["app"]  == app) &
                (scores_df["zone"] == zone)
            ].sort_values("score", ascending=False)

            if sub.empty:
                continue

            best   = sub.iloc[0]
            second = sub.iloc[1] if len(sub) > 1 else None
            prod   = best["product"]
            score  = best["score"]
            color  = PROD_COLORS.get(prod, "#888888")

            x = zi * cell_w
            y = (n_apps - 1 - ai) * cell_h

            rect = mpatches.FancyBboxPatch(
                (x + 0.035, y + 0.035),
                cell_w - 0.07, cell_h - 0.07,
                boxstyle="round,pad=0.025",
                linewidth=0, facecolor=color,
                alpha=0.87, zorder=2
            )
            ax.add_patch(rect)

            ax.text(x + cell_w / 2, y + cell_h * 0.64,
                    PROD_LABELS.get(prod, prod),
                    ha="center", va="center",
                    fontsize=9.2, fontweight="bold",
                    color="white", zorder=3)

            ax.text(x + cell_w / 2, y + cell_h * 0.38,
                    f"score = {score:.3f}",
                    ha="center", va="center",
                    fontsize=7.8, color="white",
                    alpha=0.93, zorder=3)

            if second is not None:
                ax.text(x + cell_w / 2, y + cell_h * 0.13,
                        f"2nd: {PROD_LABELS.get(second['product'], second['product'])}"
                        f" ({second['score']:.3f})",
                        ha="center", va="center",
                        fontsize=6.2, color="white",
                        alpha=0.78, zorder=3, style="italic")

    # Zone headers
    for zi, zone in enumerate(zones):
        ax.text(zi * cell_w + cell_w / 2,
                n_apps * cell_h + 0.14,
                zone, ha="center", va="bottom",
                fontsize=10.5, fontweight="bold",
                color=ZONE_COLORS.get(zone, "#555"))

    # App row labels
    for ai, app in enumerate(apps):
        y = (n_apps - 1 - ai) * cell_h + cell_h / 2
        ax.text(-0.16, y,
                app, ha="right", va="center",
                fontsize=9.5, color="#1C2D40",
                fontweight="bold")

    # Grid
    for zi in range(n_zones + 1):
        ax.axvline(zi * cell_w, color="#C8D0DC", linewidth=0.55, zorder=1)
    for ai in range(n_apps + 1):
        ax.axhline(ai * cell_h, color="#C8D0DC", linewidth=0.55, zorder=1)

    handles = [
        mpatches.Patch(facecolor=PROD_COLORS[p],
                       label=PROD_LABELS.get(p, p),
                       linewidth=0, alpha=0.87)
        for p in PROD_COLORS
    ]
    ax.legend(handles=handles, title="Product", title_fontsize=9,
              loc="lower center", bbox_to_anchor=(0.5, -0.12),
              ncol=6, fontsize=9, frameon=True,
              framealpha=0.96, edgecolor="#D0D7E0")

    ax.set_xlim(-0.06, n_zones * cell_w + 0.04)
    ax.set_ylim(-0.04, n_apps * cell_h + 0.5)
    ax.axis("off")
    ax.set_title(
        "Top-ranked precipitation product by management application and ecological zone\n"
        "Application-weighted composite scores at τ = 1.0 mm/day  |  "
        "Italic = 2nd-best product  |  West Africa 2001–2020",
        fontsize=11.5, fontweight="bold", color="#1C2D40", pad=14, loc="left"
    )

    plt.tight_layout(rect=[0.14, 0.09, 1.0, 1.0])
    out = FIGS_DIR / "fig_app01_recommendation_heatmap.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


