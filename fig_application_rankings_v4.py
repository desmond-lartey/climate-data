# FIGURE 3  — Histograms / KDE
# ════════════════════════════════════════════════════════════════════════════════
def fig_histograms(df: pd.DataFrame):
    """
    Small-multiples: one panel per product, histogram + KDE of scores
    across all zones and applications, coloured by ecological zone.
    """
    try:
        from scipy.stats import gaussian_kde
        HAS_SCIPY = True
    except ImportError:
        HAS_SCIPY = False

    products_ordered = (
        df.groupby("product")["score"]
        .median()
        .sort_values(ascending=False)
        .index.tolist()
    )

    n = len(products_ordered)
    ncols = 3
    nrows = int(np.ceil(n / ncols))

    fig, axes = plt.subplots(nrows, ncols, figsize=(14, 4.5 * nrows),
                             sharex=False, sharey=False)
    axes = axes.flatten()
    fig.patch.set_facecolor("white")

    x_all_min = df["score"].min() - 0.01
    x_all_max = df["score"].max() + 0.01

    for idx, prod in enumerate(products_ordered):
        ax = axes[idx]
        style_ax(ax)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

        prod_df = df.loc[df["product"] == prod].copy()
        color   = PROD_COLORS.get(prod, "#888")

        # Overall histogram
        ax.hist(prod_df["score"], bins=12, color=color, alpha=0.35,
                edgecolor="white", linewidth=0.6, density=True)

        # Per-zone KDE or histogram overlay
        for zone, zcolor in ZONE_COLORS.items():
            zone_scores = prod_df.loc[prod_df["zone"] == zone, "score"].values
            if len(zone_scores) < 2:
                continue
            if HAS_SCIPY:
                kde = gaussian_kde(zone_scores, bw_method=0.5)
                xs  = np.linspace(zone_scores.min() - 0.005,
                                  zone_scores.max() + 0.005, 200)
                ax.plot(xs, kde(xs), color=zcolor, linewidth=1.6,
                        alpha=0.85, label=zone)
            else:
                ax.hist(zone_scores, bins=6, color=zcolor, alpha=0.4,
                        edgecolor="white", density=True, label=zone)

        # Mean line
        mean_val = prod_df["score"].mean()
        ax.axvline(mean_val, color=color, linewidth=1.8, linestyle="--",
                   label=f"Mean = {mean_val:.3f}")

        ax.set_title(PROD_LABELS.get(prod, prod),
                     fontsize=11, fontweight="bold", color=color)
        ax.set_xlabel("Score", fontsize=9)
        ax.set_ylabel("Density", fontsize=9)
        ax.set_xlim(x_all_min, x_all_max)
        ax.legend(fontsize=7.5, framealpha=0.85, edgecolor="#CCC",
                  loc="upper left")

    # Hide any unused panels
    for idx in range(n, len(axes)):
        axes[idx].set_visible(False)

    fig.suptitle(
        "Score distributions per product — histogram + per-zone density\n"
        "Dashed line = product mean across all zones & applications  |  "
        "West Africa 2001–2020",
        fontsize=12, fontweight="bold", color="#1C2D40", y=1.01,
    )
    plt.tight_layout()
    out = FIGS_DIR / "fig_v4_03_histograms.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


