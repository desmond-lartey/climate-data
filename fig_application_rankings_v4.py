def style_ax(ax, spine_color="#CCCCCC"):
    """Light, clean axis style."""
    for spine in ax.spines.values():
        spine.set_color(spine_color)
        spine.set_linewidth(0.8)
    ax.tick_params(colors="#444444", labelsize=8.5)
    ax.yaxis.grid(True, linestyle="--", linewidth=0.5, color="#E0E0E0", alpha=0.8)
    ax.set_axisbelow(True)


# ── Load scores ───────────────────────────────────────────────────────────────
def load_scores(xlsx_path: Path) -> pd.DataFrame:
    if not xlsx_path.exists():
        raise FileNotFoundError(
            f"\nCannot find: {xlsx_path}\n"
            "Run generate_decision_tool.py first, or pass --xlsx <path>\n"
            "  → Falling back to SYNTHETIC demo data."
        )
    print(f"Reading scores from: {xlsx_path}")
    df = pd.read_excel(xlsx_path, sheet_name="SCORES", engine="openpyxl")
    df.columns = [c.lower().strip() for c in df.columns]
    df = df[df["zone"].isin(ZONES)].copy()
    df["score"] = pd.to_numeric(df["score"], errors="coerce")
    df = df.dropna(subset=["score"])
    df = df[df["app"].isin(APPS_ORDERED)].copy()

    # ── Normalise product names ───────────────────────────────────────────────
    # The Excel may use display names ("GPM IMERG", "ERA5-Land", etc.) while
    # PROD_COLORS / PROD_LABELS use underscore keys ("GPM_IMERG", "ERA5_LAND").
    # Build a best-effort mapping: strip, upper, replace spaces/hyphens with _.
    PROD_NAME_MAP = {
        # explicit overrides for known variants
        "GPM IMERG":     "GPM_IMERG",
        "GPM_IMERG":     "GPM_IMERG",
        "GPMIMERG":      "GPM_IMERG",
        "ERA5-LAND":     "ERA5_LAND",
        "ERA5_LAND":     "ERA5_LAND",
        "ERA5 LAND":     "ERA5_LAND",
        "ERA5LAND":      "ERA5_LAND",
        "PERSIANN-CDR":  "PERSIANN_CDR",
        "PERSIANN_CDR":  "PERSIANN_CDR",
        "PERSIANN CDR":  "PERSIANN_CDR",
        "PERSIANNCDR":   "PERSIANN_CDR",
        "TERRACLIMATE":  "TERRACLIMATE",
        "TERRA CLIMATE": "TERRACLIMATE",
        "TERRA-CLIMATE": "TERRACLIMATE",
        "MERRA-2":       "MERRA2",
        "MERRA2":        "MERRA2",
        "MERRA 2":       "MERRA2",
        "CHIRPS":        "CHIRPS",
    }

    def _normalise_product(name: str) -> str:
        key = str(name).strip().upper().replace("-", "_").replace(" ", "_")
        # Try exact explicit map first
        display = str(name).strip().upper()
        if display in PROD_NAME_MAP:
            return PROD_NAME_MAP[display]
        # Fallback: replace spaces/hyphens with underscores
        return key

    df["product"] = df["product"].apply(_normalise_product)

    print(f"  Loaded {len(df)} rows.")
    print(f"  Product values after normalisation: {sorted(df['product'].unique())}")
    return df


