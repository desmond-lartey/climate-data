# FIGURE 7 — Grouped bar: application × product, panels = zones
# Shows how each product ranks within every application, for each zone.
# ════════════════════════════════════════════════════════════════════════════════
def fig_app_zone_bars(df: pd.DataFrame):
    """
    Small-multiples (one panel per zone).
    Within each panel:
      X axis  = application
      Grouped bars = products
      Bar height = score
    Lets you compare all three dimensions in one figure.
    """
    products = list(PROD_COLORS.keys())
    n_prod   = len(products)
    n_apps   = len(APPS_ORDERED)
    bar_w    = 0.11
    x_base   = np.arange(n_apps)

    score_min = df["score"].min()
    score_max = df["score"].max()
    y_lo = max(0.0, score_min - 0.03)
    y_hi = min(1.02, score_max + 0.02)

    fig, axes = plt.subplots(1, len(ZONES), figsize=(22, 5.5), sharey=True)
    fig.patch.set_facecolor("white")

    for zi, (zone, ax) in enumerate(zip(ZONES, axes)):
        style_ax(ax)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.set_facecolor("#FAFAFA")

        for pi, prod in enumerate(products):
            offsets = x_base + (pi - n_prod / 2 + 0.5) * bar_w
            vals = []
            for app in APPS_ORDERED:
                row = df.loc[
                    (df["product"] == prod) &
                    (df["zone"]    == zone) &
                    (df["app"]     == app), "score"
                ]
                vals.append(row.values[0] if not row.empty else np.nan)

            bars = ax.bar(
                offsets, vals,
                width=bar_w * 0.88,
                color=PROD_COLORS.get(prod, "#888"),
                alpha=0.85, linewidth=0, zorder=3
            )

            # Mark the winning bar with a star
            for xi, (bar, val) in enumerate(zip(bars, vals)):
                if np.isnan(val):
                    continue
                best_score = df.loc[
                    (df["zone"] == zone) & (df["app"] == APPS_ORDERED[xi]),
                    "score"
                ].max()
                if abs(val - best_score) < 1e-6:
                    ax.text(
                        bar.get_x() + bar.get_width() / 2,
                        val + 0.002, "★",
                        ha="center", va="bottom", fontsize=6,
                        color=PROD_COLORS.get(prod, "#888"),
                    )

        ax.set_ylim(y_lo, y_hi)
        ax.set_xticks(x_base)
        ax.set_xticklabels(
            [APP_SHORT.get(a, a) for a in APPS_ORDERED],
            fontsize=6.8, rotation=35, ha="right", color="#333"
        )
        ax.set_title(zone, fontsize=10, fontweight="bold",
                     color=ZONE_COLORS.get(zone, "#333"), pad=6)
        if zi == 0:
            ax.set_ylabel("Score", fontsize=9)
        ax.yaxis.set_major_formatter(
            mticker.FuncFormatter(lambda v, _: f"{v:.2f}")
        )

    # Shared product legend
    prod_handles = [
        mpatches.Patch(facecolor=PROD_COLORS[p],
                       label=PROD_LABELS.get(p, p), alpha=0.85)
        for p in products
    ]
    fig.legend(handles=prod_handles, title="Product  (★ = best in cell)",
               title_fontsize=9, fontsize=8.5,
               loc="lower center", bbox_to_anchor=(0.5, -0.18),
               ncol=6, frameon=True, framealpha=0.95, edgecolor="#CCC")

    fig.suptitle(
        "Score by application, product, and ecological zone\n"
        "Each panel = one zone  |  Grouped bars = products  |  ★ = best product per application  |  "
        "West Africa 2001–2020",
        fontsize=12, fontweight="bold", color="#1C2D40", y=1.04,
    )
    plt.tight_layout()
    out = FIGS_DIR / "fig_v4_07_app_zone_bars.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


