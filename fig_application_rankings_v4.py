# FIGURE 2  — Box plots
# ════════════════════════════════════════════════════════════════════════════════
def fig_boxplots(df: pd.DataFrame):
    """
    Two panels:
      Left  — box plots per product (distribution across all zones & apps)
      Right — box plots per zone    (distribution across all products & apps)
    """
    products_ordered = (
        df.groupby("product")["score"]
        .median()
        .sort_values(ascending=False)
        .index.tolist()
    )

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    fig.patch.set_facecolor("white")

    # ── Left: by product ──────────────────────────────────────
    ax = axes[0]
    style_ax(ax)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    data_prod = [df.loc[df["product"] == p, "score"].values for p in products_ordered]
    bp = ax.boxplot(
        data_prod,
        vert=True, patch_artist=True,
        medianprops=dict(color="white", linewidth=2),
        whiskerprops=dict(linewidth=1.2),
        capprops=dict(linewidth=1.2),
        flierprops=dict(marker="o", markersize=4, alpha=0.5),
        widths=0.55,
    )
    for patch, prod in zip(bp["boxes"], products_ordered):
        patch.set_facecolor(PROD_COLORS.get(prod, "#888"))
        patch.set_alpha(0.82)
        patch.set_linewidth(0)

    # Overlay individual zone means as dots
    for xi, prod in enumerate(products_ordered, start=1):
        for zone, zcolor in ZONE_COLORS.items():
            val = df.loc[(df["product"] == prod) & (df["zone"] == zone), "score"].mean()
            if not np.isnan(val):
                ax.scatter(xi, val, color=zcolor, s=28, zorder=5,
                           edgecolors="white", linewidths=0.6)

    ax.set_xticks(range(1, len(products_ordered) + 1))
    ax.set_xticklabels(
        [PROD_LABELS.get(p, p) for p in products_ordered],
        rotation=25, ha="right", fontsize=9,
    )
    ax.set_ylabel("Application-weighted score", fontsize=10)
    ax.set_title("Score distribution by product\n(dots = per-zone means)",
                 fontsize=10.5, fontweight="bold", color="#1C2D40")

    # ── Right: by zone ─────────────────────────────────────────
    ax = axes[1]
    style_ax(ax)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    data_zone = [df[df.zone == z]["score"].values for z in ZONES]
    bp2 = ax.boxplot(
        data_zone,
        vert=True, patch_artist=True,
        medianprops=dict(color="white", linewidth=2),
        whiskerprops=dict(linewidth=1.2),
        capprops=dict(linewidth=1.2),
        flierprops=dict(marker="o", markersize=4, alpha=0.5),
        widths=0.55,
    )
    for patch, zone in zip(bp2["boxes"], ZONES):
        patch.set_facecolor(ZONE_COLORS.get(zone, "#888"))
        patch.set_alpha(0.82)
        patch.set_linewidth(0)

    # Overlay per-product means as coloured dots
    for xi, zone in enumerate(ZONES, start=1):
        for prod, pcolor in PROD_COLORS.items():
            val = df.loc[(df["zone"] == zone) & (df["product"] == prod), "score"].mean()
            if not np.isnan(val):
                ax.scatter(xi, val, color=pcolor, s=28, zorder=5,
                           edgecolors="white", linewidths=0.6)

    ax.set_xticks(range(1, len(ZONES) + 1))
    ax.set_xticklabels(ZONES, rotation=25, ha="right", fontsize=9)
    ax.set_ylabel("Application-weighted score", fontsize=10)
    ax.set_title("Score distribution by ecological zone\n(dots = per-product means)",
                 fontsize=10.5, fontweight="bold", color="#1C2D40")

    # Zone colour legend
    zone_patches = [mpatches.Patch(facecolor=ZONE_COLORS[z], label=z, alpha=0.82)
                    for z in ZONES]
    axes[1].legend(handles=zone_patches, title="Zone", fontsize=8,
                   loc="lower right", framealpha=0.9, edgecolor="#CCC")

    # Product colour legend
    prod_patches = [mpatches.Patch(facecolor=PROD_COLORS[p],
                                   label=PROD_LABELS.get(p, p), alpha=0.82)
                    for p in PRODUCTS]
    axes[0].legend(handles=prod_patches, title="Product", fontsize=8,
                   loc="lower right", framealpha=0.9, edgecolor="#CCC")

    fig.suptitle(
        "Box-plot comparison of application-weighted scores  |  West Africa 2001–2020",
        fontsize=12, fontweight="bold", color="#1C2D40", y=1.01,
    )
    plt.tight_layout()
    out = FIGS_DIR / "fig_v4_02_boxplots.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
