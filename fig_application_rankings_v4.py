# FIGURE 6 — Bubble heatmap: application × zone, bubble size = score gap,
#             bubble colour = best product, all products shown as small satellites
# ════════════════════════════════════════════════════════════════════════════════
def fig_app_bubble(df: pd.DataFrame):
    """
    Grid of application (rows) × zone (columns).
    Each cell shows:
      - A large central bubble coloured by the winning product,
        sized by the score of that winner.
      - Six small satellite dots arranged in a ring, one per product,
        sized by their individual score — so you can see all products
        and applications in one view.
    """
    apps  = APPS_ORDERED
    zones = ZONES
    products = list(PROD_COLORS.keys())
    n_apps  = len(apps)
    n_zones = len(zones)

    fig, ax = plt.subplots(figsize=(13, 8))
    fig.patch.set_facecolor("white")
    ax.set_facecolor("#F9FAFB")
    for spine in ax.spines.values():
        spine.set_color("#E0E0E0")

    # Satellite positions (angles around centre)
    sat_angles = np.linspace(0, 2 * np.pi, len(products), endpoint=False)
    sat_r = 0.30   # radius of satellite ring (in data units)

    score_min = df["score"].min()
    score_max = df["score"].max()

    def score_to_size(s, s_min=score_min, s_max=score_max,
                      min_pt=60, max_pt=900):
        return min_pt + (s - s_min) / (s_max - s_min + 1e-9) * (max_pt - min_pt)

    for ai, app in enumerate(apps):
        for zi, zone in enumerate(zones):
            cx, cy = zi, n_apps - 1 - ai   # cell centre

            cell = df.loc[(df["app"] == app) & (df["zone"] == zone)]
            if cell.empty:
                continue
            cell_sorted = cell.sort_values("score", ascending=False)

            # ── Large central bubble = winner ──────────────────
            best  = cell_sorted.iloc[0]
            bprod = best["product"]
            bscore= best["score"]
            ax.scatter(cx, cy,
                       s=score_to_size(bscore) * 1.6,
                       color=PROD_COLORS.get(bprod, "#888"),
                       alpha=0.25, zorder=2)
            ax.scatter(cx, cy,
                       s=score_to_size(bscore) * 0.55,
                       color=PROD_COLORS.get(bprod, "#888"),
                       alpha=0.85, zorder=3,
                       edgecolors="white", linewidths=0.8)

            # ── Satellite dots = all products ──────────────────
            for pi, prod in enumerate(products):
                row = cell.loc[cell["product"] == prod, "score"]
                if row.empty:
                    continue
                s_val = row.values[0]
                sx = cx + sat_r * np.cos(sat_angles[pi])
                sy = cy + sat_r * np.sin(sat_angles[pi])
                ax.scatter(sx, sy,
                           s=score_to_size(s_val, min_pt=8, max_pt=80),
                           color=PROD_COLORS.get(prod, "#888"),
                           alpha=0.82, zorder=4,
                           edgecolors="white", linewidths=0.4)

    # Grid lines
    for zi in range(n_zones):
        ax.axvline(zi - 0.5, color="#E0E0E0", linewidth=0.6)
    for ai in range(n_apps):
        ax.axhline(ai - 0.5, color="#E0E0E0", linewidth=0.6)

    # Axis labels
    ax.set_xticks(range(n_zones))
    ax.set_xticklabels(zones, fontsize=9.5, fontweight="bold")
    for tick, zone in zip(ax.get_xticklabels(), zones):
        tick.set_color(ZONE_COLORS.get(zone, "#333"))
    ax.set_yticks(range(n_apps))
    ax.set_yticklabels(
        [APP_SHORT.get(a, a).replace("\n", " ") for a in reversed(apps)],
        fontsize=9, color="#1C2D40", fontweight="bold"
    )
    ax.set_xlim(-0.6, n_zones - 0.4)
    ax.set_ylim(-0.6, n_apps - 0.4)
    ax.tick_params(length=0)

    # Legend: products
    prod_handles = [
        mpatches.Patch(facecolor=PROD_COLORS[p],
                       label=PROD_LABELS.get(p, p), alpha=0.85)
        for p in products
    ]
    ax.legend(handles=prod_handles, title="Product (large bubble = winner)",
              title_fontsize=8.5, fontsize=8,
              loc="upper left", bbox_to_anchor=(1.01, 1.0),
              framealpha=0.95, edgecolor="#CCC")

    ax.set_title(
        "Bubble heatmap: application × zone  —  all products shown\n"
        "Large central bubble = best product  |  "
        "Small satellites = all other products (size ∝ score)  |  "
        "West Africa 2001–2020",
        fontsize=11, fontweight="bold", color="#1C2D40", pad=12,
    )
    plt.tight_layout()
    out = FIGS_DIR / "fig_v4_06_app_bubble.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


