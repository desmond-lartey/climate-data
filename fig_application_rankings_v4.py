# FIGURE 1  — IPCC-style percentile band chart
# ════════════════════════════════════════════════════════════════════════════════
def fig_percentile_bands(df: pd.DataFrame):
    """
    For each product, compute score percentiles across all
    (app × zone) combinations and plot:
      - shaded band p5–p95  (light)
      - shaded band p25–p75 (darker)
      - median line
      - individual zone dots with ±1 std error bars (mean across apps per zone)
    x-axis = products ordered by median score (mimics the 'time' axis in the example).
    """
    products_ordered = (
        df.groupby("product")["score"]
        .median()
        .sort_values()
        .index.tolist()
    )

    fig, ax = plt.subplots(figsize=(12, 6))
    fig.patch.set_facecolor("white")
    style_ax(ax)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    x = np.arange(len(products_ordered))

    # ── Percentile bands ──────────────────────────────────────
    p5   = [df.loc[df["product"] == p, "score"].quantile(0.05) for p in products_ordered]
    p25  = [df.loc[df["product"] == p, "score"].quantile(0.25) for p in products_ordered]
    p50  = [df.loc[df["product"] == p, "score"].quantile(0.50) for p in products_ordered]
    p75  = [df.loc[df["product"] == p, "score"].quantile(0.75) for p in products_ordered]
    p95  = [df.loc[df["product"] == p, "score"].quantile(0.95) for p in products_ordered]

    # Overall band colour (use GPM IMERG green-ish teal for neutral)
    band_color = "#2E8B7A"

    ax.fill_between(x, p5,  p95, color=band_color, alpha=0.15, label="p5–p95 range")
    ax.fill_between(x, p25, p75, color=band_color, alpha=0.30, label="p25–p75 range")
    ax.plot(x, p50, color=band_color, linewidth=2.2,
            label="Median across all zones & apps", zorder=4)

    # ── Per-zone dots + error bars ────────────────────────────
    for zone, zcolor in ZONE_COLORS.items():
        y_means, y_stds = [], []
        for prod in products_ordered:
            sub = df.loc[(df["product"] == prod) & (df["zone"] == zone), "score"]
            y_means.append(sub.mean())
            y_stds.append(sub.std() if len(sub) > 1 else 0)
        ax.errorbar(
            x, y_means, yerr=y_stds,
            fmt="o", color=zcolor, markersize=7,
            capsize=3, linewidth=0, elinewidth=1.4,
            ecolor=zcolor, alpha=0.85,
            label=zone, zorder=5,
        )

    # ── Percentile labels at right edge ──────────────────────
    x_label = len(products_ordered) - 0.55
    for val, label in zip([p95[-1], p75[-1], p50[-1], p25[-1], p5[-1]],
                          ["p95", "p75", "median", "p25", "p5"]):
        ax.text(x_label, val, label, va="center", fontsize=8,
                color=band_color, fontweight="bold")

    ax.set_xticks(x)
    ax.set_xticklabels(
        [PROD_LABELS.get(p, p) for p in products_ordered],
        fontsize=9.5, fontweight="bold"
    )
    ax.set_ylabel("Application-weighted score", fontsize=10, color="#333")
    ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda v, _: f"{v:.2f}"))
    ax.set_xlim(-0.6, len(products_ordered) - 0.35)
    ax.set_title(
        "Score distribution by product — percentile bands + per-zone means\n"
        "Products ordered by median score  |  Dots = mean across applications per zone  |  "
        "Error bars = ±1 SD",
        fontsize=11, fontweight="bold", color="#1C2D40", pad=12,
    )

    # Legend — two rows
    handles, labels = ax.get_legend_handles_labels()
    ax.legend(
        handles, labels,
        loc="upper left", fontsize=8.5, framealpha=0.9,
        edgecolor="#CCCCCC", ncol=2,
    )

    plt.tight_layout()
    out = FIGS_DIR / "fig_v4_01_percentile_bands.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


