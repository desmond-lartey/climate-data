# FIGURE 9 — Histograms / KDE styled like fig_v4_03 but panels = applications
# Each panel = one application area.
# Overall histogram + per-product KDE lines (coloured by product).
# Second set of panels with per-zone KDE lines.
# ════════════════════════════════════════════════════════════════════════════════
def fig_app_histograms(df: pd.DataFrame):
    """
    Two rows of small-multiples, one panel per application:

    Top row    — histogram of all scores for that application +
                 per-PRODUCT KDE curves (coloured by product).
                 Dashed line = application mean across all products & zones.

    Bottom row — same histogram + per-ZONE KDE curves (coloured by zone).
    """
    try:
        from scipy.stats import gaussian_kde
        HAS_SCIPY = True
    except ImportError:
        HAS_SCIPY = False

    n_apps = len(APPS_ORDERED)
    ncols  = n_apps
    x_global_min = df["score"].min() - 0.01
    x_global_max = df["score"].max() + 0.01

    fig, axes = plt.subplots(2, ncols, figsize=(4.5 * ncols, 9),
                             sharex=True, sharey=False)
    fig.patch.set_facecolor("white")

    for ai, app in enumerate(APPS_ORDERED):
        app_df   = df.loc[df["app"] == app]
        mean_val = app_df["score"].mean()
        short    = APP_SHORT.get(app, app).replace("\n", "\n")

        # ── Top row: KDE by product ───────────────────────────
        ax_top = axes[0, ai]
        style_ax(ax_top)
        ax_top.spines["top"].set_visible(False)
        ax_top.spines["right"].set_visible(False)

        ax_top.hist(app_df["score"], bins=10, color="#CCCCCC",
                    alpha=0.45, edgecolor="white", linewidth=0.5,
                    density=True, zorder=1)

        for prod, pcolor in PROD_COLORS.items():
            pscores = app_df.loc[app_df["product"] == prod, "score"].values
            if len(pscores) < 2:
                continue
            if HAS_SCIPY:
                kde = gaussian_kde(pscores, bw_method=0.45)
                xs  = np.linspace(x_global_min, x_global_max, 300)
                ax_top.plot(xs, kde(xs), color=pcolor, linewidth=1.8,
                            alpha=0.88, label=PROD_LABELS.get(prod, prod),
                            zorder=3)
            else:
                ax_top.hist(pscores, bins=6, color=pcolor, alpha=0.4,
                            edgecolor="white", density=True,
                            label=PROD_LABELS.get(prod, prod))

        ax_top.axvline(mean_val, color="#333333", linewidth=1.6,
                       linestyle="--",
                       label=f"Mean = {mean_val:.3f}", zorder=4)

        ax_top.set_xlim(x_global_min, x_global_max)
        ax_top.set_title(short, fontsize=9.5, fontweight="bold",
                         color="#1C2D40", pad=6)
        if ai == 0:
            ax_top.set_ylabel("Density\n(by product)", fontsize=9)
        ax_top.legend(fontsize=6.5, framealpha=0.85, edgecolor="#CCC",
                      loc="upper left", ncol=1)

        # ── Bottom row: KDE by zone ───────────────────────────
        ax_bot = axes[1, ai]
        style_ax(ax_bot)
        ax_bot.spines["top"].set_visible(False)
        ax_bot.spines["right"].set_visible(False)

        ax_bot.hist(app_df["score"], bins=10, color="#CCCCCC",
                    alpha=0.45, edgecolor="white", linewidth=0.5,
                    density=True, zorder=1)

        for zone, zcolor in ZONE_COLORS.items():
            zscores = app_df.loc[app_df["zone"] == zone, "score"].values
            if len(zscores) < 2:
                continue
            if HAS_SCIPY:
                kde = gaussian_kde(zscores, bw_method=0.45)
                xs  = np.linspace(x_global_min, x_global_max, 300)
                ax_bot.plot(xs, kde(xs), color=zcolor, linewidth=1.8,
                            alpha=0.88, label=zone, zorder=3)
            else:
                ax_bot.hist(zscores, bins=6, color=zcolor, alpha=0.4,
                            edgecolor="white", density=True, label=zone)

        ax_bot.axvline(mean_val, color="#333333", linewidth=1.6,
                       linestyle="--",
                       label=f"Mean = {mean_val:.3f}", zorder=4)

        ax_bot.set_xlim(x_global_min, x_global_max)
        ax_bot.set_xlabel("Score", fontsize=8.5)
        if ai == 0:
            ax_bot.set_ylabel("Density\n(by zone)", fontsize=9)
        ax_bot.legend(fontsize=6.5, framealpha=0.85, edgecolor="#CCC",
                      loc="upper left", ncol=1)

    fig.suptitle(
        "Score distributions per application area\n"
        "Top row: per-product KDE  |  Bottom row: per-zone KDE  |  "
        "Dashed = application mean  |  West Africa 2001–2020",
        fontsize=12, fontweight="bold", color="#1C2D40", y=1.02,
    )
    plt.tight_layout()
    out = FIGS_DIR / "fig_v4_09_app_histograms.png"
    fig.savefig(out, dpi=300, bbox_inches="tight", facecolor="white")
    print(f"Saved: {out.name}")
    plt.close(fig)


